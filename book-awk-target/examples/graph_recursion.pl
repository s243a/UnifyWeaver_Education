:- use_module(unifyweaver(targets/awk_target)).
:- use_module(unifyweaver(core/recursive_compiler)).
:- use_module(library(filesex)).

% A branch, two routes from a to d, and a b-d-b cycle.
edge(a, b).
edge(a, c).
edge(b, d).
edge(c, d).
edge(d, b).

path(X, Y) :- edge(X, Y).
path(X, Y) :- edge(X, Z), path(Z, Y).

% The direct AWK ternary recognizer emits source, target, hops for each
% simple path. Its per-path cycle guard is generated by the backend;
% this unguarded Prolog relation itself can recurse forever on cycles.
path_hops(X, Y, 1) :- edge(X, Y).
path_hops(X, Y, Hops) :-
    edge(X, Z),
    path_hops(Z, Y, Hops0),
    Hops is Hops0 + 1.

:- initialization(main, main).

main(Args) :-
    ( Args = [] -> OutputDir = 'output/awk-book'
    ; Args = [OutputDir]
    ),
    make_directory_path(OutputDir),
    recursive_compiler:compile_recursive(
        path/2, [target(awk), input(embedded)], ClosureCode),
    directory_file_path(OutputDir, 'path.awk', ClosureFile),
    awk_target:write_awk_script(ClosureCode, ClosureFile),
    awk_target:compile_predicate_to_awk(path_hops/3, [], HopsCode),
    directory_file_path(OutputDir, 'path_hops.awk', HopsFile),
    awk_target:write_awk_script(HopsCode, HopsFile).
